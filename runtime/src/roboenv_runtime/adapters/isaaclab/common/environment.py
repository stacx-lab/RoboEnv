"""The small lifecycle contract between Isaac task factories and RoboEnv.

Device operations are supplied by each robot's binding, not this protocol.
WorldSession owns the clock; tick advances exactly one control interval.
"""

from typing import Protocol

from roboenv_runtime.core.types import Budget, ScoreReport


class IsaacEnvironment(Protocol):
    control_interval: float

    def tick(self) -> None: ...
    def configure_execution_mode(self, mode: str) -> None: ...
    def reset(self, seed: int) -> None: ...
    def close(self) -> None: ...
    def score(self) -> ScoreReport: ...
    def budget(self) -> Budget: ...
    def record(self) -> dict: ...

"""Convert pinned manufacturer YAM geometry using the selected Isaac Lab importer."""

import argparse
import hashlib
import json
import os
import shutil
import subprocess
import sys
import tempfile
import traceback
from pathlib import Path

from roboenv.provisioning.assets import inventory
from roboenv.provisioning.yam_assets import source_inventory

ENTRYPOINT = b'''#usda 1.0
(
    defaultPrim = "yam"
)
def Xform "yam" (
    prepend references = @native-usd/YAM.usd@
)
{
}
'''
SCHEMA = "roboenv/yam-native-conversion/3"
HISTORY = "native-usd-history"


def checksum(entries):
    return hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()


def output_inventory(directory):
    return [entry for entry in inventory(directory) if entry["path"] != "conversion.json"]


def verify(directory, *, require_current=True):
    """Verify generated bytes without Isaac; old collision conversions need an upgrade."""
    directory = Path(directory).resolve()
    link = directory / "YAM.usd"
    output = directory / "native-usd"
    if not link.exists() and not link.is_symlink() and not output.exists():
        return False
    receipt = json.loads((output / "conversion.json").read_text())
    legacy = receipt.get("schema") == "roboenv/yam-native-conversion/1"
    if legacy:
        if not link.is_symlink() or os.readlink(link) != "native-usd/YAM.usd" or not link.is_file():
            raise ValueError("YAM legacy entry point differs from its recorded conversion")
    elif (
        link.is_symlink() or not link.is_file() or link.read_bytes() != ENTRYPOINT
        or receipt.get("entrypoint_sha256") != hashlib.sha256(ENTRYPOINT).hexdigest()
    ):
        raise ValueError("YAM native entry point differs from its recorded conversion")
    source_hash = checksum(source_inventory(directory))
    if (
        receipt.get("schema") not in {
            "roboenv/yam-native-conversion/1", "roboenv/yam-native-conversion/2", SCHEMA
        }
        or receipt.get("source_files_sha256") != source_hash
        or receipt.get("output_files_sha256") != checksum(output_inventory(output))
    ):
        raise ValueError("YAM converted geometry or source inputs changed")
    history = directory / HISTORY
    if history.exists():
        for archive in history.iterdir():
            old = json.loads((archive / "conversion.json").read_text())
            if (
                archive.name != old["output_files_sha256"]
                or old["source_files_sha256"] != source_hash
                or checksum(output_inventory(archive)) != old["output_files_sha256"]
            ):
                raise ValueError("Archived YAM conversion changed")
    if receipt.get("schema") == SCHEMA:
        colliders = receipt.get("finger_colliders", [])
        if len(colliders) != 2 or {entry["finger"] for entry in colliders} != {
            "tip_left", "tip_right"
        } or any(entry["approximation"] != "convexDecomposition" for entry in colliders):
            raise ValueError("YAM finger collision conversion is incomplete")
    return not legacy and (not require_current or receipt.get("schema") == SCHEMA)


def upgrade_entrypoint(directory):
    """Repair a verified V1 resolver base while preserving its complete receipt."""
    directory = Path(directory).resolve()
    if verify(directory, require_current=False):
        raise ValueError("YAM native entrypoint is already current")
    output = directory / "native-usd"
    previous = json.loads((output / "conversion.json").read_text())
    if previous.get("schema") != "roboenv/yam-native-conversion/1":
        raise ValueError("No verified legacy YAM conversion to repair")
    receipt = {
        **previous, "schema": "roboenv/yam-native-conversion/2",
        "entrypoint_sha256": hashlib.sha256(ENTRYPOINT).hexdigest(),
        "previous_conversion": previous,
    }
    temporary = directory / ".YAM-entrypoint.tmp"
    with temporary.open("xb") as stream:
        stream.write(ENTRYPOINT)
    os.replace(temporary, directory / "YAM.usd")
    (output / "conversion.json").write_text(json.dumps(receipt, indent=2) + "\n")
    return receipt


def configure_finger_colliders(stage):
    """Decompose each existing finger collider, preserving all visual and joint geometry."""
    from pxr import PhysxSchema, Usd, UsdPhysics

    selected = {}
    for prim in list(stage.Traverse()):
        if any(finger in str(prim.GetPath()) for finger in ("tip_left", "tip_right")):
            if prim.IsInstance():
                prim.SetInstanceable(False)
    for prim in Usd.PrimRange(stage.GetPseudoRoot(), Usd.TraverseInstanceProxies()):
        path = str(prim.GetPath())
        for finger in ("tip_left", "tip_right"):
            if f"/{finger}/collisions/" in path and prim.HasAPI(UsdPhysics.MeshCollisionAPI):
                if (
                    finger in selected or prim.IsInstanceProxy()
                    or not prim.HasAPI(UsdPhysics.CollisionAPI)
                ):
                    raise ValueError("Ambiguous YAM finger collision hierarchy")
                selected[finger] = prim
    if set(selected) != {"tip_left", "tip_right"}:
        raise ValueError("Converted YAM is missing its two finger colliders")
    report = []
    for finger, prim in sorted(selected.items()):
        api = UsdPhysics.MeshCollisionAPI(prim)
        if api.GetApproximationAttr().Get() not in ("convexHull", "convexDecomposition"):
            raise ValueError("Unexpected YAM finger collision approximation")
        prim.RemoveAPI(PhysxSchema.PhysxConvexHullCollisionAPI)
        PhysxSchema.PhysxConvexDecompositionCollisionAPI.Apply(prim)
        api.CreateApproximationAttr().Set("convexDecomposition")
        report.append({"finger": finger, "path": str(prim.GetPath()),
                       "approximation": "convexDecomposition"})
    stage.GetRootLayer().Save()
    return report


def publish_upgrade(directory, target, previous):
    """Retain the complete old conversion and publish only after staging verifies."""
    directory, target = Path(directory), Path(target)
    output = directory / "native-usd"
    if (
        json.loads((output / "conversion.json").read_text()) != previous
        or checksum(output_inventory(output)) != previous["output_files_sha256"]
    ):
        raise ValueError("YAM conversion changed during upgrade")
    staged = json.loads((target / "conversion.json").read_text())
    if (
        staged.get("schema") != SCHEMA
        or staged.get("previous_conversion") != previous
        or staged.get("source_files_sha256") != checksum(source_inventory(directory))
        or staged.get("output_files_sha256") != checksum(output_inventory(target))
    ):
        raise ValueError("Staged YAM collision upgrade did not verify")
    archive = directory / HISTORY / previous["output_files_sha256"]
    archive.parent.mkdir(exist_ok=True)
    if archive.exists():
        raise ValueError("Preserve existing YAM conversion archive; concurrent upgrade refused")
    output.rename(archive)
    try:
        target.rename(output)
    except BaseException:
        archive.rename(output)
        raise


def convert(directory, *, result_file=None):
    directory = Path(directory).resolve()
    link = directory / "YAM.usd"
    output = directory / "native-usd"
    if os.environ.get("OMNI_KIT_ACCEPT_EULA", "").upper() != "YES":
        raise ValueError("Isaac Sim conversion requires explicitly accepted EULA; "
                         "no license is accepted by this tool")
    previous = None
    if link.exists() or link.is_symlink() or output.exists():
        if verify(directory):
            return json.loads((output / "conversion.json").read_text())
        if not verify(directory, require_current=False):
            upgrade_entrypoint(directory)
        previous = json.loads((output / "conversion.json").read_text())
    source = directory / "YAM.urdf"
    if not source.is_file() or not (directory / "source.json").is_file():
        raise ValueError("Prepare pinned YAM manufacturer sources first")
    before = source_inventory(directory)
    from isaaclab.app import AppLauncher

    launcher = AppLauncher(headless=True)
    try:
        from isaaclab.sim.converters import UrdfConverter, UrdfConverterCfg
        from pxr import Usd, UsdPhysics

        # Keep failed staging for diagnosis. USD can retain mapped layers, and
        # deleting them on NFS can mask the actual error with an ENOTEMPTY failure.
        tmp = Path(tempfile.mkdtemp(prefix=".yam-conversion-", dir=directory.parent))
        try:
            target = Path(tmp) / "native-usd"
            if previous:
                shutil.copytree(output, target)
                stage = Usd.Stage.Open(str(target / "YAM.usd"))
                receipt = {**previous, "previous_conversion": previous}
            else:
                cfg = UrdfConverterCfg(
                    asset_path=str(source), usd_dir=str(target), usd_file_name="YAM.usd",
                    fix_base=True, merge_fixed_joints=False, make_instanceable=False,
                    force_usd_conversion=False, collision_from_visuals=True,
                    collider_type="convex_hull", self_collision=False,
                    joint_drive=UrdfConverterCfg.JointDriveCfg(
                        drive_type="force", target_type="position",
                        gains=UrdfConverterCfg.JointDriveCfg.PDGainsCfg(stiffness=0.0, damping=0.0),
                    ),
                )
                converted = UrdfConverter(cfg)
                stage = Usd.Stage.Open(converted.usd_path)
                receipt = {"config": cfg.to_dict()}
                receipt["config"].update(asset_path="YAM.urdf", usd_dir="native-usd")
            joints = {
                prim.GetName() for prim in stage.Traverse()
                if prim.IsA(UsdPhysics.RevoluteJoint) or prim.IsA(UsdPhysics.PrismaticJoint)
            }
            if joints != {f"joint{i}" for i in range(1, 9)}:
                raise ValueError("Converted YAM lost or added actuator joints")
            if not any(prim.GetName() == "camera" for prim in stage.Traverse()):
                raise ValueError("Converted YAM lost its fixed optical frame")
            colliders = configure_finger_colliders(stage)
            if source_inventory(directory) != before:
                raise ValueError("Native conversion modified its source inputs")
            receipt.update(
                schema=SCHEMA, entrypoint_sha256=hashlib.sha256(ENTRYPOINT).hexdigest(),
                source_files_sha256=checksum(before),
                output_files_sha256=checksum(output_inventory(target)),
                native_joints=sorted(joints), finger_colliders=colliders,
                collision_geometry="manufacturer visuals: convex bodies and decomposed fingers",
                self_collision=False, fixed_sensor_frame_preserved=True,
                native_motion_verified=False,
            )
            (target / "conversion.json").write_text(json.dumps(receipt, indent=2) + "\n")
            if previous:
                publish_upgrade(directory, target, previous)
            else:
                target.rename(output)
        except BaseException:
            print(f"Failed YAM conversion staging retained at {tmp}", file=sys.stderr, flush=True)
            raise
        else:
            tmp.rmdir()
        if not previous:
            link.write_bytes(ENTRYPOINT)
        if not verify(directory):
            raise ValueError("Published YAM conversion did not verify")
        if result_file is not None:
            Path(result_file).write_text(json.dumps({"passed": True, "receipt": receipt}))
        return receipt
    except BaseException as error:
        traceback.print_exc(file=sys.stderr)
        sys.stderr.flush()
        if result_file is not None:
            Path(result_file).write_text(json.dumps({
                "passed": False, "error": type(error).__name__ + ": " + str(error)
            }))
        raise
    finally:
        launcher.app.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--worker-result", type=Path, help=argparse.SUPPRESS)
    args = parser.parse_args()
    if args.worker_result is not None:
        receipt = convert(args.directory, result_file=args.worker_result)
        # Already-current conversions never boot Kit, so also cover that return.
        if not args.worker_result.exists():
            args.worker_result.write_text(json.dumps({"passed": True, "receipt": receipt}))
        return
    # Kit fast shutdown may terminate Python with zero while unwinding an error;
    # graceful extension shutdown can crash after saving valid USD. Keep the
    # default native shutdown in a child and require a receipt saved before it.
    with tempfile.TemporaryDirectory(prefix="roboenv-yam-conversion-status-") as tmp:
        result_file = Path(tmp) / "result.json"
        child = subprocess.run(
            [sys.executable, "-m", "roboenv.provisioning.yam_usd", str(args.directory),
             "--worker-result", str(result_file)],
            check=False, timeout=1700,
        )
        if child.returncode != 0 or not result_file.is_file():
            raise RuntimeError("YAM conversion worker failed or left no completion receipt")
        result = json.loads(result_file.read_text())
        if result.get("passed") is not True or not verify(args.directory):
            raise RuntimeError(result.get("error", "YAM conversion did not verify"))
        print(json.dumps(result["receipt"], indent=2))


if __name__ == "__main__":
    main()
